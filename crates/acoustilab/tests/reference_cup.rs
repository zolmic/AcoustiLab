//! The open reference cup (spec Section 17, docs/reference-cup.md): the
//! dimensions, the CAD include and the netlist agree; every configuration of
//! the protocol solves within its operating limits; the frozen blind
//! predictions match their manifest, whose own SHA-256 is pinned here; the
//! drift of the current engine from them is reported without failing; and
//! the validation pipeline, run on synthetic sessions from the virtual rig,
//! passes a true cup within its tolerances, fails a cup with a model-form
//! error, and reports missing files and sidecars that break the protocol.
//!
//! The end-to-end tests run the model at level 0 (lumped cavities) for both
//! the true cup and the fit, so that they stay fast in debug builds; the
//! pipeline is the same at level 1 (`full_session_at_level_1`, ignored:
//! run it with `cargo test --release -p acoustilab --test reference_cup --
//! --ignored --nocapture`).

use acoustilab::expr::PValue;
use acoustilab::params::{Overrides, Parametric};
use acoustilab::validation::predict::{self, Frozen};
use acoustilab::validation::session::{self, Severity, ValidateOptions};
use acoustilab::validation::simulate::{self, SimulateOptions};
use acoustilab::validation::{Files, Protocol};
use acoustilab::Circuit;
use serde_json::{json, Value};
use std::path::{Path, PathBuf};

/// SHA-256 of every frozen manifest. A frozen prediction is never changed:
/// a new one goes into a new version directory, and its manifest's hash is
/// added here in the same commit, where a reviewer sees it.
const FROZEN: &[(&str, &str)] = &[(
    "v1",
    "29dd01983da36b58737833b4eb1bc0b97b6645354df5233120fa01454dd0014e",
)];

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn read(rel: &str) -> String {
    std::fs::read_to_string(root().join(rel)).unwrap_or_else(|e| panic!("{rel}: {e}"))
}

fn read_dir(dir: &Path) -> Files {
    let mut files = Files::new();
    for e in std::fs::read_dir(dir).unwrap_or_else(|e| panic!("{}: {e}", dir.display())) {
        let e = e.unwrap();
        if e.path().is_file() {
            files.insert(
                e.file_name().into_string().unwrap(),
                std::fs::read(e.path()).unwrap(),
            );
        }
    }
    files
}

fn predictions_dir() -> PathBuf {
    root().join("validation/reference_cup/predictions")
}

fn frozen_v1() -> Frozen {
    Frozen::load(&read_dir(&predictions_dir().join("v1"))).expect("load v1")
}

// ----- Dimensions, CAD and netlist ------------------------------------------

/// The include tools/refcup/dims_to_scad.py writes, reproduced.
fn scad_include(dims: &Value) -> String {
    let mut s = String::from(
        "// Generated by tools/refcup/dims_to_scad.py from\n\
         // validation/reference_cup/dimensions.json. Do not edit: edit the JSON\n\
         // and run the script (cargo test checks that this file is current).\n",
    );
    s += &format!("// Licence: {}\n\n", dims["licence"].as_str().unwrap());
    for (name, d) in dims["dimensions"].as_object().unwrap() {
        let x = d["value"].as_f64().unwrap();
        let text = if x.fract() == 0.0 {
            format!("{}", x as i64)
        } else {
            format!("{x}")
        };
        s += &format!("{name} = {text};\n");
    }
    s
}

#[test]
fn dimensions_scad_and_netlist_agree() {
    let dims: Value =
        serde_json::from_str(&read("validation/reference_cup/dimensions.json")).unwrap();
    assert_eq!(
        read("validation/reference_cup/geometry/dimensions.scad"),
        scad_include(&dims),
        "geometry/dimensions.scad is stale: run tools/refcup/dims_to_scad.py"
    );
    let net: Value = serde_json::from_str(&read("examples/reference_cup.json")).unwrap();
    let params = net["parameters"].as_object().unwrap();
    let entries = dims["dimensions"].as_object().unwrap();
    let mut modelled = 0;
    for (name, d) in entries {
        let p = params.get(name);
        if d["model"].as_bool().unwrap() {
            modelled += 1;
            let p = p.unwrap_or_else(|| {
                panic!("'{name}' is a model dimension but not a netlist parameter")
            });
            assert_eq!(
                p["value"], d["value"],
                "'{name}': netlist and dimensions differ"
            );
            assert_eq!(
                p.get("tolerance"),
                d.get("tolerance"),
                "'{name}': the netlist's tolerance must be the dimension's"
            );
        } else {
            assert!(
                p.is_none(),
                "'{name}' is CAD-only but also a netlist parameter"
            );
        }
    }
    for (name, p) in params {
        let group = p.get("group").and_then(Value::as_str).unwrap_or("");
        if group == "Cup geometry" || group == "Driver geometry" {
            assert!(
                entries.get(name).is_some_and(|d| d["model"] == json!(true)),
                "netlist geometry parameter '{name}' is not a model dimension in dimensions.json"
            );
        }
    }
    assert!(modelled >= 15, "{modelled} model dimensions");
    // The volumes the netlist derives, against the CAD's closed forms.
    let p = Parametric::parse(&read("examples/reference_cup.json")).unwrap();
    let v: std::collections::BTreeMap<String, f64> = p
        .values(&Overrides::new())
        .unwrap()
        .into_iter()
        .filter_map(|(k, v)| v.as_num().map(|x| (k, x)))
        .collect();
    let dim = |k: &str| entries[k]["value"].as_f64().unwrap();
    let area = |d: f64| std::f64::consts::PI * d * d / 4.0;
    let rear = area(dim("cup_inner_diameter_mm")) * dim("rear_depth_mm")
        - (area(dim("retainer_outer_diameter_mm")) - area(dim("retainer_inner_diameter_mm")))
            * dim("retainer_thickness_mm")
        - area(dim("driver_rear_boss_diameter_mm"))
            * (dim("driver_overall_depth_mm") - dim("driver_body_depth_mm"));
    assert!((v["rear_volume_cm3"] - rear / 1000.0).abs() < 1e-12);
    let front = area(dim("cup_inner_diameter_mm"))
        * (dim("pad_ring_height_mm") + dim("gasket_compressed_mm"))
        + area(dim("lip_inner_diameter_mm")) * (dim("lip_thickness_mm") + dim("driver_gasket_mm"))
        + v["driver_Sd_cm2"] * 100.0 * dim("diaphragm_setback_mm");
    assert!((v["front_volume_cm3"] - front / 1000.0).abs() < 1e-12);
}

