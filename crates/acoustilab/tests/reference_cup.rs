// ----- The pipeline on synthetic sessions ------------------------------------

/// The frozen set with only some configurations kept (to bound the run
/// time of a test).
fn restricted(ids: &[&str]) -> Frozen {
    let mut f = frozen_v1();
    f.protocol
        .configurations
        .retain(|c| ids.contains(&c.id.as_str()));
    assert_eq!(f.protocol.configurations.len(), ids.len());
    f
}

fn lumped() -> Overrides {
    Overrides::from([("fidelity".to_string(), PValue::Num(0.0))])
}

fn files_of(s: std::collections::BTreeMap<String, String>) -> Files {
    s.into_iter().map(|(k, v)| (k, v.into_bytes())).collect()
}

fn sim(f: &Frozen, truth: &[(&str, f64)], netlist: Option<String>, seed: u64) -> Files {
    let mut o = SimulateOptions {
        seed,
        netlist_text: netlist,
        points_per_octave: 12.0,
        ..SimulateOptions::default()
    };
    o.truth = lumped();
    for (k, v) in truth {
        o.truth.insert(k.to_string(), PValue::Num(*v));
    }
    files_of(simulate::simulate(f, &o).expect("simulate"))
}

fn validate(f: &Frozen, files: &Files, anchor: bool) -> session::Report {
    let opts = ValidateOptions {
        extra_overrides: lumped(),
        anchor_driver: anchor,
        fit_points_per_octave: Some(12.0),
        max_evaluations: 100,
    };
    session::validate(f, files, &opts, &mut |_| {}).expect("validate")
}

fn spec_pass(r: &session::Report, id: &str) -> bool {
    let m = r.measurement(id).unwrap();
    assert!(m.errors.is_empty(), "{id}: {:?}", m.errors);
    m.acceptance
        .iter()
        .find(|a| a.variant == "spec")
        .unwrap_or_else(|| panic!("{id}: no acceptance run"))
        .pass
}

/// The frozen netlist with the driver's internal rear path the model
/// leaves out: a volume behind the diaphragm and an acoustic mass (the
/// rear holes) in series with the rear chamber.
fn with_internal_rear_path(netlist: &str, mass_kg_per_m4: f64, volume_cm3: f64) -> String {
    let mut d: Value = serde_json::from_str(netlist).unwrap();
    let els = d["elements"].as_array_mut().unwrap();
    let drv = els.iter_mut().find(|e| e["id"] == "drv").unwrap();
    drv["nodes"][3] = json!("=if(in_cup, 'a_int', 'ambient')");
    els.push(json!({"id": "int_vol", "type": "cavity", "node": "a_int",
                    "volume_cm3": volume_cm3, "enabled": "=in_cup"}));
    els.push(
        json!({"id": "int_vent", "type": "acoustic_impedance", "nodes": ["a_int", "a_rear"],
                    "M_kg_per_m4": mass_kg_per_m4, "R_Pa_s_per_m3": 3e4, "enabled": "=in_cup"}),
    );
    d["nodes"]
        .as_array_mut()
        .unwrap()
        .push(json!({"id": "a_int", "domain": "acoustic", "enabled": "=in_cup"}));
    d.to_string()
}

#[test]
fn a_true_cup_within_its_tolerances_passes() {
    let f = restricted(&["driver_free", "iec_ref", "t43_ref"]);
    // Every perturbation is inside the frozen tolerances, and the leak and
    // front volume (fitted) are far from their nominal values.
    let truth = [
        ("driver_Bl_factor", 1.04),
        ("driver_compliance_factor", 1.2),
        ("driver_Rms_factor", 0.9),
        ("driver_Mms_g", 0.31),
        ("mesh_rayl", 240.0),
        ("front_volume_factor", 1.06),
    ];
    let files = sim(&f, &truth, None, 7);
    let t0 = std::time::Instant::now();
    let r = validate(&f, &files, true);
    println!(
        "{}\nvalidated in {:.1} s",
        r.summary(),
        t0.elapsed().as_secs_f64()
    );
    assert!(r.verdict.complete, "{:?}", r.verdict);
    assert!(r.verdict.synthetic);
    assert_eq!(r.verdict.sidecar_errors, 0);
    for id in ["iec_ref_p", "t43_ref_p"] {
        assert!(spec_pass(&r, id), "{}", r.summary());
        let a = r.measurement(id).unwrap();
        let fitted = &a.acceptance[0].fitted;
        let volume = fitted
            .iter()
            .find(|p| p.name == "front_volume_factor")
            .unwrap();
        assert!((volume.value - 1.06).abs() < 0.03, "{id}: {volume:?}");
    }
    // The driver anchor recovers the true driver from its free-air
    // impedance, and the anchored runs pass too.
    let anchor = r.driver_anchor.as_ref().expect("anchor");
    let get = |n: &str| anchor.fitted.iter().find(|p| p.name == n).unwrap().value;
    assert!(
        (get("driver_Bl_factor") / 1.04 - 1.0).abs() < 0.02,
        "{anchor:?}"
    );
    for id in ["iec_ref_p", "t43_ref_p"] {
        let m = r.measurement(id).unwrap();
        assert!(m
            .acceptance
            .iter()
            .any(|a| a.variant == "driver_anchored" && a.pass));
    }
    // The blind comparison is reported apart from the acceptance: here the
    // true cup differs from the frozen nominal, so its residuals are not
    // zero, and nothing in it is a pass or fail.
    let b = r.measurement("iec_ref_p").unwrap().blind.as_ref().unwrap();
    assert!(b
        .bands
        .iter()
        .all(|x| x.pass.is_none() && x.bound_db.is_none()));
    // The verdict covers the reference states of the (restricted)
    // protocol: here the IEC and Type 4.3 ones.
    assert_eq!(r.verdict.reference_pass, Some(true));
}

#[test]
fn a_model_form_error_fails_and_a_small_one_passes() {
    let f = restricted(&["iec_ref"]);
    // The driver's rear holes as a 350 kg/m^4 mass (two 2.7 mm holes
    // through 1 mm, with their end corrections) resonate with the rear
    // chamber near 400 Hz: the fit of leak and front volume cannot absorb
    // that, and the bounds catch it.
    let large = with_internal_rear_path(&f.netlist_text, 350.0, 2.0);
    let r = validate(&f, &sim(&f, &[], Some(large), 3), false);
    assert!(!spec_pass(&r, "iec_ref_p"), "{}", r.summary());
    let a = &r.measurement("iec_ref_p").unwrap().acceptance[0];
    println!(
        "large: {:?}",
        a.bands
            .iter()
            .map(|b| (b.max_abs_db, b.at_hz))
            .collect::<Vec<_>>()
    );
    assert!(
        a.bands[0].pass == Some(false) && a.bands[0].max_abs_db > 4.0,
        "{:?}",
        a.bands
    );
    // A tenth of it stays within the bounds.
    let small = with_internal_rear_path(&f.netlist_text, 3.0, 0.1);
    let r = validate(&f, &sim(&f, &[], Some(small), 3), false);
    let a = &r.measurement("iec_ref_p").unwrap().acceptance[0];
    println!(
        "small: {:?}",
        a.bands
            .iter()
            .map(|b| (b.max_abs_db, b.at_hz))
            .collect::<Vec<_>>()
    );
    assert!(spec_pass(&r, "iec_ref_p"), "{}", r.summary());
}

#[test]
fn missing_files_and_protocol_violations_are_reported() {
    let f = restricted(&["cup_free_sealed", "iec_ref", "t43_ref"]);
    let mut files = sim(&f, &[], None, 11);
    // t43_ref_p never measured, one seating of iec_ref_z lost.
    files.retain(|k, _| !k.starts_with("t43_ref_p_") && !k.starts_with("iec_ref_z_s5."));
    // A wrong fixture, a smoothed export, a different drive and a missing
    // sidecar.
    let edit = |files: &mut Files, name: &str, f: &dyn Fn(&mut Value)| {
        let mut v: Value = serde_json::from_slice(&files[name]).unwrap();
        f(&mut v);
        files.insert(name.into(), v.to_string().into_bytes());
    };
    edit(&mut files, "iec_ref_p_s1.frd.sidecar.json", &|v| {
        v["fixture"] = json!("head and torso simulator")
    });
    edit(&mut files, "iec_ref_p_s2.frd.sidecar.json", &|v| {
        v["smoothing"] = json!("1/6")
    });
    edit(&mut files, "iec_ref_p_s3.frd.sidecar.json", &|v| {
        v["drive"] = json!({"voltage_V": 1})
    });
    files.remove("cup_free_sealed_z_s2.zma.sidecar.json");
    files.insert("notes.txt".into(), b"bench notes".to_vec());
    let r = validate(&f, &files, false);
    assert!(!r.verdict.complete);
    assert_eq!(r.verdict.missing, vec!["t43_ref_p".to_string()]);
    assert!(
        r.verdict.incomplete.contains(&"iec_ref_z".to_string()),
        "{:?}",
        r.verdict
    );
    assert!(
        r.verdict.incomplete.contains(&"iec_ref_p".to_string()),
        "{:?}",
        r.verdict
    );
    assert_eq!(r.verdict.reference_pass, None);
    let p = r.measurement("iec_ref_p").unwrap();
    assert_eq!(p.seatings, 2, "three files break the protocol");
    let errs = |file: &str, field: &str| {
        p.issues
            .iter()
            .any(|i| i.file == file && i.field == field && i.severity == Severity::Error)
    };
    assert!(errs("iec_ref_p_s1.frd", "fixture"));
    assert!(errs("iec_ref_p_s2.frd", "smoothing"));
    assert!(errs("iec_ref_p_s3.frd", "drive"));
    let z = r.measurement("cup_free_sealed_z").unwrap();
    assert!(z
        .issues
        .iter()
        .any(|i| i.field == "sidecar" && i.severity == Severity::Error));
    assert!(r.unrecognised_files.contains(&"notes.txt".to_string()));
    let text = r.summary();
    assert!(
        text.contains("Incomplete session") && text.contains("t43_ref_p"),
        "{text}"
    );
    // The report says the acceptance was not evaluated rather than passing.
    assert!(text.contains("not evaluated"), "{text}");
}

