#[test]
fn every_configuration_solves_within_its_operating_limits() {
    let text = read("validation/reference_cup/protocol.json");
    let protocol = Protocol::parse(&text).unwrap();
    // A coarse grid: this checks the netlist, not the curves.
    let freqs: Vec<f64> = (0..12).map(|k| 20.0 * 2f64.powi(k)).collect();
    let p = acoustilab::validation::netlist_on_grid(&read("examples/reference_cup.json"), &freqs)
        .unwrap();
    protocol.check_against(&p).unwrap();
    for c in &protocol.configurations {
        let circuit = Circuit::from_parametric(&p, &protocol.overrides_for(c)).unwrap();
        let r = circuit.solve().unwrap();
        let limits: Vec<String> = r
            .warnings
            .iter()
            .filter(|w| w.limit.is_some())
            .map(|w| w.message.clone())
            .collect();
        assert!(limits.is_empty(), "{}: {limits:?}", c.id);
    }
}

// ----- Frozen predictions ----------------------------------------------------

#[test]
fn frozen_predictions_match_their_manifest() {
    let mut versions = Vec::new();
    for e in std::fs::read_dir(predictions_dir()).unwrap() {
        let e = e.unwrap();
        if e.path().is_dir() {
            versions.push(e.file_name().into_string().unwrap());
        }
    }
    versions.sort();
    assert!(versions.contains(&"v1".to_string()), "{versions:?}");
    for v in &versions {
        let pinned = FROZEN
            .iter()
            .find(|(name, _)| name == v)
            .unwrap_or_else(|| panic!("prediction version '{v}' is not pinned in FROZEN"))
            .1;
        let r = predict::verify(&read_dir(&predictions_dir().join(v)));
        assert!(r.ok, "{v}: {:#?}", r.problems);
        assert_eq!(
            r.manifest_sha256.as_deref(),
            Some(pinned),
            "{v}: the manifest changed; frozen predictions are never edited"
        );
        assert!(r.files_checked > 40, "{v}: {} files", r.files_checked);
    }
}

#[test]
fn verification_refuses_any_change() {
    let dir = predictions_dir().join("v1");
    let files = read_dir(&dir);
    let mut changed = files.clone();
    let csv = changed.get_mut("iec_ref_p.csv").unwrap();
    let last = csv.len() - 2;
    csv[last] = if csv[last] == b'1' { b'2' } else { b'1' };
    let r = predict::verify(&changed);
    assert!(
        !r.ok && r.problems.iter().any(|p| p.contains("iec_ref_p.csv")),
        "{:?}",
        r.problems
    );
    assert!(Frozen::load(&changed).is_err());
    let mut extra = files.clone();
    extra.insert("iec_ref_p_v2.csv".into(), b"1,2\n".to_vec());
    assert!(!predict::verify(&extra).ok);
    let mut missing = files;
    missing.remove("t43_ref_z.envelope.csv");
    assert!(!predict::verify(&missing).ok);
}

#[test]
fn frozen_predictions_are_complete_and_consistent() {
    let f = frozen_v1();
    let m = &f.manifest;
    assert_eq!(m["version"], "v1");
    assert_eq!(
        m["git"]["dirty"],
        json!(false),
        "v1 must come from a clean tree"
    );
    assert!(m["git"]["commit"].as_str().is_some_and(|c| c.len() == 40));
    assert_eq!(
        m["netlist"]["sha256"].as_str().unwrap(),
        acoustilab::validation::sha256_hex(f.netlist_text.as_bytes())
    );
    for c in m["configurations"].as_array().unwrap() {
        let mc = &c["monte_carlo"];
        assert_eq!(mc["runs"], json!(f.protocol.mc_runs), "{}", c["id"]);
        assert_eq!(mc["failed"], json!(0), "{}: {}", c["id"], mc["failures"]);
    }
    for (conf, meas) in f.protocol.measurements() {
        let nominal = &f.nominal[&meas.id];
        let env = &f.envelopes[&meas.id];
        assert_eq!(nominal.freqs_hz, env.freqs, "{}", meas.id);
        assert!(env.freqs[0] >= conf.band.0 && *env.freqs.last().unwrap() <= conf.band.1);
        let level = match env.quantity {
            acoustilab::io::Quantity::Pressure => nominal.level_db(),
            _ => nominal.magnitude.clone(),
        };
        for (i, l) in level.iter().enumerate() {
            assert_eq!(*l, env.nominal[i], "{} at {} Hz", meas.id, env.freqs[i]);
            assert!(
                env.min[i] <= env.p5[i] && env.p5[i] <= env.median[i],
                "{} at {}",
                meas.id,
                env.freqs[i]
            );
            assert!(
                env.median[i] <= env.p95[i] && env.p95[i] <= env.max[i],
                "{} at {}",
                meas.id,
                env.freqs[i]
            );
            assert_eq!(env.n[i], f.protocol.mc_runs);
        }
        // The frozen sidecar states the protocol's conditions.
        let sc = &nominal.sidecar;
        assert_eq!(
            sc.reference_point.as_deref(),
            Some(meas.reference_point.as_str())
        );
        assert_eq!(sc.compensation.as_deref(), Some("none"));
        assert!(sc.drive.is_some());
        if let Some(fx) = conf.sidecar.get("fixture") {
            assert_eq!(sc.fixture.as_deref(), fx.as_str());
        }
    }
}

